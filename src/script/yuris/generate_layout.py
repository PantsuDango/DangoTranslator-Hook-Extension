"""Generate the native matcher constants from the Go-embedded display contract."""
import json
from pathlib import Path
import sys


def generate(source, destination):
    spec = json.loads(Path(source).read_text(encoding="utf-8"))
    lines = ["// Generated by generate_layout.py; edit yuris_display_layout.json.", "#pragma once"]
    for name in ("word",):
        code = bytes.fromhex(spec[name]["code"])
        mask = bytearray([1] * len(code))
        for offset in spec[name]["relocations"]:
            if offset < 0 or offset + 4 > len(code):
                raise ValueError("invalid relocation")
            mask[offset:offset + 4] = bytes(4)
        for suffix, values in (("Code", code), ("Mask", mask)):
            lines.append("constexpr unsigned char " + name + suffix + "[] = {" +
                         ",".join(str(value) for value in values) + "};")
    Path(destination).write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    generate(*sys.argv[1:])
